# Ejemplos de los tipos de datos básicos disponibles en Python

# Datos de tipo entero
edad = 25
cantidad = 100

print("Edad:", edad)
print("Cantidad:", cantidad)


# Datos que contienen números decimales
precio = 9.99
altura = 1.75

print("Precio:", precio)
print("Altura:", altura)


# Variables utilizadas para almacenar texto
nombre = "Juan"
mensaje = "¡Hola, mundo!"

print("Nombre:", nombre)
print("Mensaje:", mensaje)


# Valores que solamente pueden ser verdadero o falso
es_mayor_de_edad = True
tiene_descuento = False

print("¿Es mayor de edad?:", es_mayor_de_edad)
print("¿Tiene descuento?:", tiene_descuento)